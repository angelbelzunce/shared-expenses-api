-- Esquema inicial de Sharex (el mismo que generó Hibernate en local con ddl-auto: update).

CREATE TABLE users (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email    VARCHAR(255) NOT NULL,
    name     VARCHAR(255),
    password VARCHAR(255) NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE groups (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE group_members (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    joined_at TIMESTAMP(6) NOT NULL,
    user_role VARCHAR(255) NOT NULL,
    group_id  BIGINT NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
    user_id   BIGINT NOT NULL REFERENCES users (id),
    CONSTRAINT group_members_user_role_check CHECK (user_role IN ('MEMBER', 'ADMIN')),
    CONSTRAINT uk_group_members_group_user UNIQUE (group_id, user_id)
);

CREATE TABLE group_invitations (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at        TIMESTAMP(6) NOT NULL,
    invitation_status VARCHAR(255) NOT NULL,
    group_id          BIGINT NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
    invited_by_id     BIGINT NOT NULL REFERENCES users (id),
    invited_user_id   BIGINT NOT NULL REFERENCES users (id),
    CONSTRAINT group_invitations_status_check CHECK (invitation_status IN ('PENDING', 'ACCEPTED', 'REJECTED'))
);

CREATE TABLE payment (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount           NUMERIC(38, 2),
    created_at       TIMESTAMP(6) NOT NULL,
    description      VARCHAR(255),
    payment_status   VARCHAR(255),
    title            VARCHAR(255),
    transaction_type VARCHAR(255),
    group_id         BIGINT NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
    user_id          BIGINT NOT NULL REFERENCES users (id),
    CONSTRAINT payment_status_check CHECK (payment_status IN ('PENDING', 'PAID')),
    CONSTRAINT payment_transaction_type_check CHECK (transaction_type IN ('INCOME', 'EXPENSE'))
);

CREATE TABLE payment_shares (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount     NUMERIC(38, 2) NOT NULL,
    paid_at    TIMESTAMP(6),
    status     VARCHAR(255) NOT NULL,
    payment_id BIGINT NOT NULL REFERENCES payment (id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES users (id),
    CONSTRAINT payment_shares_status_check CHECK (status IN ('PENDING', 'SETTLED', 'CONFIRMED')),
    CONSTRAINT uk_payment_shares_payment_user UNIQUE (payment_id, user_id)
);
