CREATE TABLE share_history (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acting_user_id BIGINT NOT NULL REFERENCES users (id),
    share_id       BIGINT NOT NULL REFERENCES payment_shares (id) ON DELETE CASCADE,
    from_status    VARCHAR(255) NOT NULL,
    to_status      VARCHAR(255) NOT NULL,
    modified_at    TIMESTAMP(6) NOT NULL,
    CONSTRAINT share_history_from_status_check CHECK (from_status IN ('PENDING', 'SETTLED', 'CONFIRMED')),
    CONSTRAINT share_history_to_status_check CHECK (to_status IN ('PENDING', 'SETTLED', 'CONFIRMED'))
);
